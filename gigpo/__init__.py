__all__ = ["core_gigpo"]


def __getattr__(name):  # PEP 562 lazy submodule import
    if name in __all__:
        import importlib
        module = importlib.import_module(f"{__name__}.{name}")
        globals()[name] = module
        return module
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
